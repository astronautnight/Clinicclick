
'use server';
/**
 * @fileOverview Provides an AI-powered patient diagnosis and treatment suggestion flow.
 *
 * - diagnosePatientSymptoms - A function that takes patient symptoms and returns AI-generated
 *   suggestions for diagnosis and treatment, along with a critical disclaimer.
 * - AIDiagnosisInput - The input type for the diagnosePatientSymptoms function.
 * - AIDiagnosisOutput - The return type for the diagnosePatientSymptoms function.
 */

import {ai} from '@/ai/genkit';
import {z} from 'genkit';
import type { AIDiagnosisInput, AIDiagnosisOutput } from '@/types';

const AIDiagnosisInputSchema = z.object({
  symptoms: z.string().describe('A detailed description of the patient\'s signs and symptoms.'),
  patientContext: z.string().optional().describe('Optional: Brief context about the patient (e.g., age, gender, relevant medical history snippets).'),
});

const AIDiagnosisOutputSchema = z.object({
  suggestedDiagnosis: z.string().describe('A potential diagnosis based on the provided symptoms. This should be clearly marked as a suggestion.'),
  suggestedTreatmentPlan: z.string().describe('A potential treatment plan or next steps. This should also be marked as a suggestion.'),
  importantDisclaimer: z.string().describe('A mandatory disclaimer stating that this is an AI suggestion, not professional medical advice, and a qualified healthcare professional must be consulted for any medical concerns or decisions.'),
  confidence: z.string().optional().describe('An optional field for the AI to state its confidence level (e.g., High, Medium, Low) if it can determine one.')
});

export async function diagnosePatientSymptoms(input: AIDiagnosisInput): Promise<AIDiagnosisOutput> {
  return diagnosePatientFlow(input);
}

const defaultDisclaimer = "IMPORTANT: This information is generated by an AI and is for informational purposes only. It is NOT a substitute for professional medical advice, diagnosis, or treatment. Always seek the advice of your physician or other qualified health provider with any questions you may have regarding a medical condition. Do not disregard professional medical advice or delay in seeking it because of something you have read or received from this AI assistant.";

const diagnosePatientPrompt = ai.definePrompt({
  name: 'diagnosePatientPrompt',
  input: {schema: AIDiagnosisInputSchema},
  output: {schema: AIDiagnosisOutputSchema},
  prompt: `You are an AI medical assistant for a dental clinic. Your role is to provide potential diagnoses and treatment suggestions based on the signs and symptoms provided by a dental professional.
You are NOT a real doctor and your suggestions are NOT medical advice.

Analyze the following patient information:
Symptoms: {{{symptoms}}}
{{#if patientContext}}Patient Context: {{{patientContext}}}{{/if}}

Based on this, provide:
1.  A 'suggestedDiagnosis': List potential dental conditions or issues. Preface with "Possible diagnosis based on symptoms:".
2.  A 'suggestedTreatmentPlan': Suggest potential next steps, treatments, or further investigations. Preface with "Suggested next steps/treatment considerations:".
3.  An 'importantDisclaimer': This field is MANDATORY. You MUST include the following disclaimer, or a very close equivalent if the model's safety guidelines prevent exact reproduction: "${defaultDisclaimer}"
4.  Optionally, a 'confidence' level (e.g., "High", "Medium", "Low") if you can assess it.

Your output MUST be in a valid JSON format matching the provided schema. Ensure the disclaimer is prominent and clear.
Prioritize common dental conditions unless symptoms strongly indicate otherwise.
If symptoms are vague or insufficient, state that and recommend collecting more specific information before suggesting any diagnosis.
`,
});

const diagnosePatientFlow = ai.defineFlow(
  {
    name: 'diagnosePatientFlow',
    inputSchema: AIDiagnosisInputSchema,
    outputSchema: AIDiagnosisOutputSchema,
  },
  async (input: AIDiagnosisInput) => {
    const {output} = await prompt(input);
    if (!output) {
        // Fallback in case the model fails to produce structured output
        // or if there's an unexpected issue.
        return {
            suggestedDiagnosis: "Could not determine a diagnosis. The AI model did not return a valid response.",
            suggestedTreatmentPlan: "Unable to suggest a treatment plan.",
            importantDisclaimer: defaultDisclaimer,
            confidence: "N/A"
        };
    }
    // Ensure the disclaimer is always present, even if the model forgets.
    if (!output.importantDisclaimer || output.importantDisclaimer.length < 50) {
        output.importantDisclaimer = defaultDisclaimer;
    }
    return output;
  }
);
